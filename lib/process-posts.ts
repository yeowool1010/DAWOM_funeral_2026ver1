/** 상세 페이지에서 굵은 소제목으로 쓰는 본문 줄(로마 숫자 또는 `1.`~`9.` 단, `**`로 시작하는 줄은 본문 굵게만 적용) */
export function isProcessArticleSectionHeading(text: string): boolean {
  const t = text.trimStart();
  if (t.startsWith("*")) return false;
  if (/^(I{1,3}|IV|VII|VI|V)\.\s/.test(t)) return true;
  // 장례 비용 글 등: "1. 시간은 금!", "2. 키워드", 핵심 정리 소항목은 본문 소제목으로 두고 h2 제외
  if (
    /^[1-9]\d*\.\s*(시간은 금|키워드|장례식장 선택이|음식 비용은|장례용품은|지원 제도는|한 문장)/.test(
      t,
    )
  ) {
    return false;
  }

  // 종교별장례절차(불교식 상례)에서 1.~15. 절차 항목은 소제목(h2)로 올리지 않음
  // 예: "1.다비식", "2.삼귀의례", "10.사홍 서원" 등은 본문 흐름으로 유지
  if (
    /^\d+\.\s*(다비식|삼귀의례|약력보고|착어|창혼|헌화|독경|추도사|소향|사홍\s*서원|중생무변|번뇌무진|법문무량|불도무상|폐식)/.test(
      t,
    )
  ) {
    return false;
  }
  return /^[1-9]\d*\.\s*/.test(t);
}

/** 메타 설명 등 — 본문 `**강조**` 마커 제거 */
export function stripProcessBodyEmphasis(text: string): string {
  return text.replaceAll("**", "");
}

